#!/usr/bin/env python3
"""Generate native guide catalogs and translations. Run with --check in CI."""
import argparse
import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
DATA = json.loads((ROOT / 'docs/keyboard-guide/catalog.json').read_text())
STRINGS = DATA['strings']
LANGUAGES = ['en', 'ru', 'es', 'uz', 'kk', 'pt', 'zh-Hans']
MARKER = '/* Generated keyboard guide; edit docs/keyboard-guide/catalog.json. */'

def quote(value):
    return json.dumps(value, ensure_ascii=False)

def text_key(value):
    return 'guide.' + value if value in STRINGS else value

def outputs():
    swift = ['// Generated by scripts/checks/generate_keyboard_guide.py.', 'import Foundation',
        'struct KeyboardGuideEntry: Identifiable {',
        '    let id: Int', '    let keys: [String]', '    let action: String',
        '    let mode: String', '    let hold: Bool', '}',
        'struct KeyboardGuideGroup: Identifiable {',
        '    let id: String', '    let note: String', '    let entries: [KeyboardGuideEntry]', '}',
        'enum KeyboardGuideCatalog {', '    static let manualURL = URL(string: ' + quote(DATA['manualURL']) + ')!',
        '    static let groups: [KeyboardGuideGroup] = [']
    kotlin = ['// Generated by scripts/checks/generate_keyboard_guide.py.',
        'package com.vitalyart.aulaf75maxdriver',
        'internal data class GuideEntry(val keys: List<String>, val action: Int, val fallback: String, val mode: String, val hold: Boolean)',
        'internal data class GuideGroup(val title: Int, val note: Int, val entries: List<GuideEntry>)',
        'internal const val GUIDE_MANUAL_URL = ' + quote(DATA['manualURL']),
        'internal val guideGroups = listOf(']
    c = ['/* Generated by scripts/checks/generate_keyboard_guide.py. */',
        'typedef struct { const char *first, *second, *action, *mode; gboolean hold; } GuideEntry;',
        'typedef struct { const char *title, *note; const GuideEntry *entries; int count; } GuideGroup;',
        '#define GUIDE_MANUAL_URL ' + quote(DATA['manualURL'])]
    for gi, group in enumerate(DATA['groups']):
        swift += ['        KeyboardGuideGroup(id: ' + quote(text_key(group['id'])) + ', note: ' + quote(text_key(group['note'])) + ', entries: [']
        kotlin += ['    GuideGroup(R.string.guide_' + group['id'] + ', R.string.guide_' + group['note'] + ', listOf(']
        c += ['static const GuideEntry guide_entries_' + str(gi) + '[] = {']
        for ri, row in enumerate(group['rows']):
            keys = ', '.join(map(quote, row['keys']))
            swift += [f'            KeyboardGuideEntry(id: {ri}, keys: [{keys}], action: {quote(text_key(row["action"]))}, mode: {quote(row["mode"])}, hold: {str(row["hold"]).lower()}),']
            action = 'R.string.guide_' + row['action'] if row['action'] in STRINGS else '0'
            kotlin += [f'        GuideEntry(listOf({keys}), {action}, {quote(row["action"])}, {quote(row["mode"])}, {str(row["hold"]).lower()}),']
            c += ['    {' + ', '.join([quote(row['keys'][0]), quote(row['keys'][1]) if len(row['keys']) > 1 else 'NULL', quote(text_key(row['action'])), quote(row['mode']), 'TRUE' if row['hold'] else 'FALSE']) + '},']
        swift += ['        ]),']; kotlin += ['    )),']; c += ['};']
    swift += ['    ]', '}']; kotlin += [')']; c += ['static const GuideGroup guide_groups[] = {']
    for gi, group in enumerate(DATA['groups']):
        c += ['    {' + ', '.join([quote(text_key(group['id'])), quote(text_key(group['note'])), 'guide_entries_' + str(gi), str(len(group['rows']))]) + '},']
    c += ['};']
    yield ROOT / 'Sources/AulaF75MaxDriver/Views/KeyboardGuideCatalog.swift', '\n'.join(swift) + '\n'
    yield ROOT / 'android/app/src/main/java/com/vitalyart/aulaf75maxdriver/KeyboardGuideCatalog.kt', '\n'.join(kotlin) + '\n'
    yield ROOT / 'Sources/CAulaLinuxGTK/KeyboardGuideCatalog.inc', '\n'.join(c) + '\n'
    for lang in LANGUAGES:
        assert all(lang in translations and translations[lang] for translations in STRINGS.values())
        for app in ['AulaF75MaxDriver', 'AulaLinuxApp']:
            path = ROOT / f'Sources/{app}/Resources/{lang}.lproj/Localizable.strings'
            base = path.read_text().split(MARKER)[0].rstrip()
            block = '\n'.join(quote('guide.' + k) + ' = ' + quote(v[lang]) + ';' for k, v in STRINGS.items())
            yield path, base + '\n\n' + MARKER + '\n' + block + '\n'
        folder = {'en': 'values', 'zh-Hans': 'values-zh-rCN'}.get(lang, 'values-' + lang)
        block = '\n'.join('    <string name="guide_' + k + '">' + escape(v[lang]).replace("'", "\\'") + '</string>' for k, v in STRINGS.items())
        yield ROOT / f'android/app/src/main/res/{folder}/keyboard_guide.xml', '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/checks/generate_keyboard_guide.py. -->\n<resources>\n' + block + '\n</resources>\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        raise SystemExit('Regenerate keyboard guide: ' + ', '.join(stale))
    print('Keyboard guide catalogs and seven-language translations are current.')
